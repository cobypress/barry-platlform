import { test } from "node:test";
import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { buildDigest } from "../build.ts";
import { digestTexts } from "../checked.ts";
import { ENGINE_TEXT_DIRS } from "../engine-texts-scan.ts";
import { buildReport } from "../../narrative/sections.ts";
import { automatic } from "./readiness-scenarios.ts";

// Our own notes never reach a customer (DECISIONS.md 775): no text we serve
// names QUESTIONS.md, DECISIONS.md or another of our documents, a decision by
// its number, or a ticket. One did: a metric's assumption ended "(QUESTIONS.md 3)".

const INTERNAL = /QUESTIONS\.md|DECISIONS\.md|ARCHITECTURE\.md|ROADMAP\.md|(?<![\w./])docs\/|\b[Dd]ecisions? \d{3}\b|\bKAN-\d+/;
const ROOT = fileURLToPath(new URL("../../..", import.meta.url));

/**
 * Strings in the folders whose text can reach a customer that are never
 * served, each with why: a worker's log line, the generated engine-texts
 * file's own header, and `npm run questions`, our own report of which
 * QUESTIONS.md items real orgs settle, which no customer sees.
 */
const NOT_SERVED = new Set([
  "src/facts/questions-report.ts: ",
  "src/facts/questions.ts: ",
  "src/engine/org-words.ts: A sentence with the org's words was made outside any health check's own org-word store",
  "src/digest/engine-texts-scan.ts: // Generated by src/digest/engine-texts-scan.ts",
]);

function* sources(dir: string): Generator<string> {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name !== "__tests__") yield* sources(p);
    } else if (e.name.endsWith(".ts")) yield p;
  }
}

/** A string's words as a reader could see them: a style sheet's comments and a link's address aren't read. */
const readable = (text: string): string => text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/https?:\/\/\S+/g, "");

function referencesIn(path: string): string[] {
  const sf = ts.createSourceFile(path, readFileSync(path, "utf8"), ts.ScriptTarget.Latest, true);
  const out: string[] = [];
  const visit = (n: ts.Node): void => {
    let text: string | null = null;
    if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) text = n.text;
    else if (ts.isTemplateExpression(n)) text = [n.head.text, ...n.templateSpans.map((s) => s.literal.text)].join(" ");
    if (text !== null && INTERNAL.test(readable(text))) {
      const key = `${relative(ROOT, path)}: ${text.trim().slice(0, 100)}`;
      if (![...NOT_SERVED].some((k) => key.startsWith(k))) out.push(key);
    }
    if (!ts.isTemplateExpression(n)) ts.forEachChild(n, visit);
    else n.templateSpans.forEach((s) => ts.forEachChild(s, visit));
  };
  visit(sf);
  return out;
}

test("no string in the folders whose text can reach a customer names our own documents, decisions or tickets", () => {
  const found = ENGINE_TEXT_DIRS.flatMap((d) => [...sources(join(ROOT, "src", d))]).flatMap(referencesIn);
  assert.deepEqual(found, []);
});

test("and no text the synthetic org's automatic digest serves does", () => {
  const report = buildReport(automatic.input);
  const digest = buildDigest({ report, pseudonyms: automatic.pseudonyms, inventory: null, madeAt: "2026-11-25T09:00:00.000Z" });
  assert.deepEqual(digestTexts(digest).filter((t) => INTERNAL.test(t)), []);
  assert.ok(digestTexts(digest).some((t) => t.startsWith("Last run is Salesforce's own record of when each report was last run")));
});

test("the check sees what it should", () => {
  for (const t of ["See QUESTIONS.md 3", "(DECISIONS.md 682)", "as decision 682 says", "KAN-102", "docs/BULK-API.md"]) assert.ok(INTERNAL.test(readable(t)), t);
  for (const t of ["https://architect.salesforce.com/docs/architect/guide", ".x { margin: 0; /* DECISIONS.md 505 */ }", "the decision is yours", "10 decisions"]) assert.ok(!INTERNAL.test(readable(t)), t);
});
